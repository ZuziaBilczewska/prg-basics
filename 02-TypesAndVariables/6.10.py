# String manipulation.
#

movie = "The Lord of the Rings: The Return of the King"

# Liczba znaków
print("Number of characters:", len(movie))

# Tekst wielkimi literami
print(movie.upper())

# Tekst małymi literami
print(movie.lower())

# Liczba wystąpień litery e
print('Number of "e" letters:', movie.count("e"))

# Pozycja słowa "Lord"
print('Position of "Lord":', movie.find("Lord"))

# Pozycja słowa "dragon"
print('Position of "dragon":', movie.find("dragon"))